#!/usr/bin/env bash
#
# Repository hygiene. Exits 1 on any finding, each as `file:line: rule: text`.
#   a) a tracked file that should be ignored (local junk, secrets, build output, local-only docs)
#   b) an untracked file that is neither ignored nor allowlisted
#   c) AI-code smells in tracked code outside docs/
# Generated shadcn primitives (web/src/components/ui) are skipped by the smell scan but stay under
# eslint and tsc. Allowlist: scripts/hygiene_allow.txt, one `path-glob | line-regex | reason` per line. The
# default is empty. Run from anywhere; operates on the git repository containing this script.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
ALLOW="${HYGIENE_ALLOW:-scripts/hygiene_allow.txt}"
FAILS=0
report() { printf '%s\n' "$1"; FAILS=$((FAILS + 1)); }

allowed() { # <path> <text> -> 0 when an allowlist entry covers it
  [ -f "$ALLOW" ] || return 1
  local g r reason
  while IFS='|' read -r g r reason; do
    g="$(printf '%s' "$g" | sed 's/^ *//;s/ *$//')"; r="$(printf '%s' "$r" | sed 's/^ *//;s/ *$//')"
    case "$g" in ''|'#'*) continue ;; esac
    [ -n "$(printf '%s' "$reason" | tr -d ' ')" ] || continue # an entry without a reason does not count
    # shellcheck disable=SC2254
    case "$1" in $g) printf '%s' "$2" | grep -Eq -- "$r" && return 0 ;; esac
  done < "$ALLOW"
  return 1
}

# ---- a) tracked files that must not be tracked -------------------------------------------
BAD_PATH='(^|/)(\.DS_Store|__pycache__|node_modules|\.next|coverage|htmlcov|\.idea|\.claude|\.plan-facts|dist|build|\.vercel)(/|$)|(^|/)\.env(\.(?!example$).*)?$|\.(log|pyc|pem)$|(^|/)\.coverage$|\.tfstate|[^/]*tfplan[^/]*$|(^|/)crash(\.[^/]*)?\.log$|(^|/)\.terraform/|(^|/)[^/]*key[^/]*\.json$|^docs/ai/|(^|/)PLAN\.md$|^docs/versions\.md$'
while IFS= read -r f; do
  allowed "$f" "$f" || report "$f:1: tracked-junk: tracked file that belongs in .gitignore or local-only"
done < <(git ls-files | perl -ne "print if m{$BAD_PATH}")
git ls-files -- '.vscode/*' | grep -vE '^\.vscode/(settings|extensions|launch|tasks)\.json$' | while IFS= read -r f; do
  echo "$f:1: tracked-junk: only shared .vscode settings may be tracked"
done > /tmp/.hyg.$$ ; if [ -s /tmp/.hyg.$$ ]; then while IFS= read -r l; do report "$l"; done < /tmp/.hyg.$$; fi; rm -f /tmp/.hyg.$$

# ---- b) untracked, not ignored, not allowlisted ------------------------------------------
while IFS= read -r f; do
  allowed "$f" "$f" || report "$f:1: untracked: neither ignored, tracked nor allowlisted"
done < <(git ls-files --others --exclude-standard)

# ---- c) smells in tracked code outside docs/ ---------------------------------------------
SCAN_PL=$(cat <<'PL'
use strict; use warnings; use utf8;
binmode(STDOUT, ":utf8");
my $prod = shift; # 1 when the file is a production path (print/console rules apply)
my $ext = shift;
my $file = shift;
my $old_id = "AD" . "R"; # the retired planning-id prefix, joined so this file does not spell it
my @prev = ("");
open(my $fh, "<:encoding(UTF-8)", $file) or exit 0;
my $n = 0;
while (my $l = <$fh>) {
  chomp $l; $n++;
  my $p1 = $prev[-1] // "";
  sub hit { my ($r, $msg) = @_; print "$file:$n: $r: $msg\n"; }
  my $is_comment = $l =~ m{^\s*(#|//|\*|/\*)};
  hit("planning-id", $l) if $l =~ /\b$old_id-\d|\bWP-|PLAN(?:\.md)?\s*§|§\s?\d|STRETCH S\d|\bG2-|Case \d \(§/;
  hit("tool-name", $l) if $l =~ /\b(?:claude|anthropic|chatgpt|copilot|openai|llm)\b|\bgpt-|as an ai\b/i;
  hit("generated-marker", $l) if $l =~ /\b(?:auto-?)?generated by\b|\@generated\b/i;
  hit("emoji", $l) if $l =~ /[\x{1F300}-\x{1FAFF}\x{2600}-\x{27BF}\x{2B50}\x{2B1B}\x{2B1C}\x{2190}-\x{21FF}\x{2713}\x{2717}]/;
  # suppressions must name a specific code and give a reason
  if ($l =~ /#\s*type:\s*ignore/) { hit("suppression", $l) unless $l =~ /type:\s*ignore\[[a-z-]+(?:,\s*[a-z-]+)*\]\s+(?:#|--)\s*\S.{5,}/; }
  if ($l =~ /#\s*noqa/)           { hit("suppression", $l) unless $l =~ /noqa:\s*[A-Z]+\d+(?:,\s*[A-Z]+\d+)*\s+(?:#|--)\s*\S.{5,}/; }
  if ($l =~ /eslint-disable/)     { hit("suppression", $l) unless $l =~ /eslint-disable(?:-next-line|-line)?\s+[@\w\/-]+(?:,\s*[@\w\/-]+)*\s+--\s+\S.{5,}/; }
  hit("suppression", $l) if $l =~ /\@ts-ignore/;
  if ($l =~ /\@ts-expect-error/)  { hit("suppression", $l) unless $l =~ /\@ts-expect-error\s*[:-]+\s*\S.{5,}/; }
  if ($ext =~ /^(?:ts|tsx)$/ && $l =~ /(?::\s*any\b|\bas any\b|<any>|\bany\[\])/ && !$is_comment) {
    hit("any-type", $l) unless $l =~ m{//\s*\S} || $p1 =~ m{^\s*(?://|/\*|\*)\s*\S};
  }
  if ($prod) {
    hit("debug-print", $l) if $ext eq "py" && $l =~ /(?<![\w.])print\(/ && !$is_comment;
    hit("debug-print", $l) if $ext =~ /^(?:ts|tsx|js|mjs)$/ && $l =~ /\bconsole\.(?:log|debug)\(/ && !$is_comment;
  }
  hit("todo", $l) if $l =~ /\b(?:TODO|FIXME)\b(?!\([A-Za-z0-9_.@-]+\):\s*\S.{7,})/;
  hit("stub", $l) if $l =~ /\bpass\s*#\s*(?:TODO|FIXME)|implement me/i;
  if ($l =~ /raise NotImplementedError/) { my $ctx = join("\n", @prev); hit("stub", $l) unless $ctx =~ /abstractmethod|Protocol/; }
  hit("restating-comment", $l) if $l =~ m{^\s*(?:#|//|\*|/\*+)\s*(?:This (?:function|method)\b|Note:)};
  push @prev, $l; shift @prev if @prev > 3;
}
PL
)

is_code() { case "$1" in
  *.py|*.ts|*.tsx|*.js|*.mjs|*.sh|*.go|*.tf|*.sql|*.yml|*.yaml|Makefile|*/Makefile|*/Dockerfile|Dockerfile) return 0 ;; esac; return 1; }
skip_smell() { case "$1" in
  docs/*|packages/ui/src/components/ui/*|*.lock|pnpm-lock.yaml|*/generated/*|contracts/openapi.json|.husky/_/*|scripts/repo_hygiene.sh|scripts/repo_hygiene_selftest.sh|.terraform.lock.hcl) return 0 ;; esac; return 1; }

while IFS= read -r f; do
  is_code "$f" || continue
  skip_smell "$f" && continue
  [ -f "$f" ] || continue
  prod=0
  case "$f" in backend/app/*|apps/*/src/*|packages/*/src/*) case "$f" in */tests/*|*.test.*|apps/*/src/api/*) ;; *) prod=1 ;; esac ;; esac
  ext="${f##*.}"
  while IFS= read -r hit; do
    [ -z "$hit" ] && continue
    allowed "$f" "$hit" || report "$hit"
  done < <(perl -e "$SCAN_PL" "$prod" "$ext" "$f")
done < <(git ls-files)

# ---- d) dead relative links in the README and docs ----------------------------------------
# A link must resolve to a tracked file or directory: a file that only exists on this machine
# would pass an existence test here and 404 on GitHub.
TRACKED="$(mktemp)"; git ls-files > "$TRACKED"
while IFS= read -r md; do
  [ -f "$md" ] || continue
  while IFS=$'\t' read -r line target; do
    allowed "$md" "$target" && continue
    case "$target" in http://*|https://*|mailto:*|\#*|'') continue ;; esac
    path="${target%%#*}"; path="${path%%\?*}"
    [ -n "$path" ] || continue
    resolved="$(perl -MFile::Spec -e 'my ($d,$p)=@ARGV; my $r=$p=~m{^/}?substr($p,1):File::Spec->catfile($d,$p); my @o; for my $s (split m{/}, $r) { next if $s eq "" || $s eq "."; if ($s eq "..") { pop @o } else { push @o,$s } } print join("/",@o)' "$(dirname "$md")" "$path")"
    if ! grep -qxF -- "$resolved" "$TRACKED" && ! grep -q -- "^${resolved}/" "$TRACKED"; then
      report "$md:$line: dead-link: $target does not resolve to a tracked file"
    fi
  done < <(perl -ne 'while (/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g) { print "$.\t$1\n" }' "$md")
done < <(git ls-files 'README.md' 'docs/*.md' 'docs/**/*.md')
rm -f "$TRACKED"

# ---- d) the retired clinic name ----------------------------------------------------------
# The clinic is "Idyllic Clinic" everywhere. Only the migration that renames existing rows may still
# name the old one (it has to, to find them). The pattern is written so this line does not match itself.
while IFS= read -r l; do
  report "$l: retired-name: the clinic is Idyllic Clinic; only the rename migration may name the old name"
done < <(git grep -n -I -i '[m]vule' -- . ':!backend/migrations/versions/0011_idyllic_clinic_name.py' | cut -d: -f1,2)

if [ "$FAILS" -eq 0 ]; then echo "repo-hygiene: OK"; else echo "repo-hygiene: $FAILS finding(s)"; fi
[ "$FAILS" -eq 0 ]
