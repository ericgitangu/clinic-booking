#!/usr/bin/env bash
#
# Proves scripts/repo_hygiene.sh by seeding: each case copies the tracked files to a throwaway
# git repo under /tmp, adds ONE bad (or good) file, and checks the exit code and message.
# Nothing is written to this repository.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
BASE="$WORK/base"
mkdir -p "$BASE"
( cd "$ROOT" && git ls-files -z | xargs -0 -I{} cp --parents {} "$BASE" 2>/dev/null ) || \
( cd "$ROOT" && git ls-files -z | tar -cf - --null -T - ) | ( cd "$BASE" && tar -xf - )
cp "$ROOT/scripts/repo_hygiene.sh" "$BASE/scripts/repo_hygiene.sh"
( cd "$BASE" && git init -q && git add -A && git -c user.email=t@t -c user.name=t commit -qm base )

# Seeded cases run against a minimal repo (the script, an empty allowlist, the real .gitignore):
# the full tree is only needed for the one "unmodified tree passes" control.
MIN="$WORK/min"
mkdir -p "$MIN/scripts"
cp "$ROOT/scripts/repo_hygiene.sh" "$ROOT/scripts/hygiene_allow.txt" "$MIN/scripts/"
cp "$ROOT/.gitignore" "$MIN/.gitignore"
( cd "$MIN" && git init -q && git add -A && git -c user.email=t@t -c user.name=t commit -qm base )

PASSES=0; FAILS=0; N=0
ok()  { PASSES=$((PASSES + 1)); printf 'PASS  %s\n' "$1"; }
bad() { FAILS=$((FAILS + 1)); printf 'FAIL  %s\n' "$1"; }

# case <name> <want: pass|<substring>> <tracked: 1|0> <path> <content>
run_case() {
  local name="$1" want="$2" tracked="$3" path="$4" content="$5" d out rc
  N=$((N + 1)); d="$WORK/c$N"; cp -R "$MIN" "$d"
  mkdir -p "$d/$(dirname "$path")"; printf '%s\n' "$content" > "$d/$path"
  [ "$tracked" = 1 ] && ( cd "$d" && git add -f "$path" )
  out="$(cd "$d" && bash scripts/repo_hygiene.sh 2>&1)"; rc=$?
  if [ "$want" = pass ]; then
    [ "$rc" -eq 0 ] && ok "$name" || bad "$name (exit $rc: $(printf '%s' "$out" | head -2 | tr '\n' '|'))"
  else
    if [ "$rc" -ne 0 ] && grep -qF -- "$want" <<<"$out" && grep -qE -- "^[^ ]+:[0-9]+: " <<<"$out"; then ok "$name"
    else bad "$name (exit $rc, wanted '$want': $(printf '%s' "$out" | head -2 | tr '\n' '|'))"; fi
  fi
}

echo "== controls =="
N=$((N + 1)); d="$WORK/c$N"; cp -R "$BASE" "$d"
( cd "$d" && bash scripts/repo_hygiene.sh >/dev/null 2>&1 ) && ok "unmodified tree passes" || bad "unmodified tree passes"
echo "== a) tracked junk =="
for p in .DS_Store .env .env.local app/.env.production x.log coverage/a.xml htmlcov/index.html .coverage \
         pkg/__pycache__/m.pyc m.pyc node_modules/a/b.js web/.next/x.js infra/.terraform/p a.tfstate a.tfstate.backup \
         .vercel/project.json .idea/w.xml .vscode/other.json .claude/settings.json .plan-facts/f docs/ai/PROMPTS.md \
         certs/server.pem service-account-key.json keys/my-key.json dist/a.js build/a.o \
         docs/architecture/PLAN.md docs/versions.md; do
  run_case "tracked $p" "tracked-junk" 1 "$p" "x"
done
run_case "tracked .env.example is allowed"        pass 1 ".env.example" "A=1"
run_case "tracked .terraform.lock.hcl is allowed" pass 1 "infra/terraform/.terraform.lock.hcl" "x"
run_case "tracked .vscode/settings.json is allowed" pass 1 ".vscode/settings.json" "{}"

echo "== b) untracked files =="
run_case "untracked scratch file"  "untracked" 0 "scratch.txt" "x"
N=$((N + 1)); d="$WORK/c$N"; cp -R "$MIN" "$d"; printf 'x\n' > "$d/scratch.txt"
printf 'scratch.txt | . | local scratch kept for review\n' >> "$d/scripts/hygiene_allow.txt"
( cd "$d" && bash scripts/repo_hygiene.sh >/dev/null 2>&1 ) && ok "allowlisted untracked file passes" || bad "allowlisted untracked file passes"
N=$((N + 1)); d="$WORK/c$N"; cp -R "$MIN" "$d"; printf 'x\n' > "$d/scratch.txt"
printf 'scratch.txt | . |\n' >> "$d/scripts/hygiene_allow.txt"
( cd "$d" && bash scripts/repo_hygiene.sh >/dev/null 2>&1 ) && bad "allowlist entry without a reason is ignored" || ok "allowlist entry without a reason is ignored"
N=$((N + 1)); d="$WORK/c$N"; cp -R "$MIN" "$d"; printf '.vscode/\n' >> "$d/.gitignore"; mkdir -p "$d/.vscode"; printf 'x\n' > "$d/.vscode/a.json"
( cd "$d" && bash scripts/repo_hygiene.sh >/dev/null 2>&1 ) && ok "ignored untracked file passes" || bad "ignored untracked file passes"

echo "== c) smells (backend/app/seed.py, web/src/seed.ts) =="
PY=backend/app/seed.py; TS=web/src/seed.ts
smell() { run_case "$1" "$2" 1 "$3" "$4"; }
smell "planning id ADR"        "planning-id" $PY '# see ADR-0014 for why'
smell "planning id WP"         "planning-id" $PY '# done in WP-08'
smell "planning id PLAN §"     "planning-id" $PY '# PLAN §13.2'
smell "planning id bare §"     "planning-id" $TS '// per §4 of the doc'
smell "planning id STRETCH"    "planning-id" $PY '# STRETCH S1 only'
smell "planning id G2"         "planning-id" $PY '# G2-12 fix'
smell "planning id Case"       "planning-id" $PY '# Case 3 (§7)'
for t in claude anthropic chatgpt copilot openai gpt-4 LLM; do smell "tool name $t" "tool-name" $PY "# written with $t"; done
smell "as an AI"               "tool-name" $PY '# as an AI I cannot'
smell "generated by marker"    "generated-marker" $PY '# Generated by a tool'
smell "emoji in a comment"     "emoji" $PY '# done ✅'
smell "emoji rocket in code"   "emoji" $TS 'const s = "🚀";'
smell "bare type: ignore"      "suppression" $PY 'x = f()  # type: ignore'
smell "type: ignore no reason" "suppression" $PY 'x = f()  # type: ignore[arg-type]'
smell "bare noqa"              "suppression" $PY 'import os  # noqa'
smell "noqa no reason"         "suppression" $PY 'import os  # noqa: F401'
smell "eslint-disable bare"    "suppression" $TS '/* eslint-disable */'
smell "eslint-disable no reason" "suppression" $TS '// eslint-disable-next-line no-console'
smell "@ts-ignore"             "suppression" $TS '// @ts-ignore -- because'
smell "@ts-expect-error bare"  "suppression" $TS '// @ts-expect-error'
smell "any without comment"    "any-type" $TS 'export function f(x: any) { return x; }'
smell "as any"                 "any-type" $TS 'const y = z as any;'
smell "print in prod path"     "debug-print" $PY 'print("hi")'
smell "console.log in prod"    "debug-print" $TS 'console.log("hi");'
smell "TODO bare"              "todo" $PY '# TODO fix later'
smell "FIXME bare"             "todo" $TS '// FIXME'
smell "TODO owner no reason"   "todo" $PY '# TODO(eric):'
smell "pass # TODO stub"       "stub" $PY 'def f() -> None:
    pass  # TODO(eric): write it later on'
smell "NotImplementedError"    "stub" $PY 'def f() -> None:
    raise NotImplementedError'
smell "implement me"           "stub" $PY '# implement me'
smell "This function comment"  "restating-comment" $PY '# This function adds numbers'
smell "This method comment"    "restating-comment" $TS '// This method returns x'
smell "Note: comment"          "restating-comment" $PY '# Note: returns x'

echo "== smell controls (must pass) =="
smell "type: ignore with code and reason" pass $PY 'x = f()  # type: ignore[arg-type]  # httpx wants a narrower type'
smell "noqa with code and reason"  pass $PY 'import os  # noqa: F401  # re-exported for callers'
smell "eslint-disable with reason" pass $TS '// eslint-disable-next-line no-control-regex -- rejecting control characters'
smell "any with justification"     pass $TS '// any: third-party callback has no type
export function f(x: any) { return x; }'
smell "TODO with owner and reason" pass $PY '# TODO(eric): drop once the vendor ships the fix'
smell "NotImplementedError in abstractmethod" pass $PY 'import abc
class A(abc.ABC):
    @abc.abstractmethod
    def f(self) -> None:
        raise NotImplementedError'
smell "print outside a production path" pass backend/scripts/tool.py 'print("cli output")'
smell "smell words inside docs/"   pass docs/notes.md 'Mentions ADR-0014 and Claude here.'
smell "planning id in a test file" "planning-id" backend/tests/x.py '# WP-08'

echo
echo "repo_hygiene selftest: $PASSES passed, $FAILS failed"
[ "$FAILS" -eq 0 ]
